static int m1_address_scramble(int address, uint16_t key)
{
    static const int p1[8][16] = {
        {15,14,10,7,1,2,3,8,0,12,11,13,6,9,5,4},
        {7,1,8,11,15,9,2,3,5,13,4,14,10,0,6,12},
        {8,6,14,3,10,7,15,1,4,0,2,5,13,11,12,9},
        {2,8,15,9,3,4,11,7,13,6,0,10,1,12,14,5},
        {1,13,6,15,14,3,8,10,9,4,7,12,5,2,0,11},
        {11,15,3,4,7,0,9,2,6,14,12,1,8,5,10,13},
        {10,5,13,8,6,15,1,14,11,9,3,0,12,7,4,2},
        {9,3,7,0,2,12,4,11,14,10,5,8,15,13,1,6},
    };
    static const int keyswap[16] = { 12,0,2,4,8,15,7,13,10,1,3,6,11,9,14,5 };
    static const int finalswap[16] = { 7,15,14,6,5,13,12,4,11,3,10,2,9,1,8,0 };

    const int block = (address >> 16) & 7;
    int aux = address & 0xffff;

    aux ^= bitswap16(key, keyswap);
    int bs[16];
    for (int k = 0; k < 16; k++) bs[k] = p1[block][15 - k];
    aux = bitswap16((uint16_t)aux, bs);
    aux ^= m1_address_0_7_xor[(aux >> 8) & 0xff];
    aux ^= m1_address_8_15_xor[aux & 0xff] << 8;
    aux = bitswap16((uint16_t)aux, finalswap);

    return (block << 16) | aux;
}

void NeoCmc50M1Decrypt(std::vector<uint8_t>& m1)
{
    const size_t size = m1.size() < 0x80000 ? m1.size() : 0x80000;
    if (size < 0x10000) return;
    // the CMC50 sums the first 64KB of the M1 and uses it as the key
    uint16_t key = 0;
    for (size_t i = 0; i < 0x10000; i++) key = uint16_t(key + m1[i]);
    std::vector<uint8_t> out(size);
    for (size_t i = 0; i < size; i++)
    {
        const size_t src = (size_t)m1_address_scramble((int)i, key);
        out[i] = src < m1.size() ? m1[src] : 0xff;
    }
    std::memcpy(m1.data(), out.data(), size);
}

void NeoPcm2Decrypt(std::vector<uint8_t>& v, int value)
{
    // swap address lines on the whole ROM (16bit words)
    const size_t words = v.size() / 2;
    const int blk = value / 2;
    std::vector<uint16_t> buf(blk);
    uint16_t* rom = reinterpret_cast<uint16_t*>(v.data());
    for (size_t i = 0; i + blk <= words; i += blk)
    {
        std::memcpy(buf.data(), &rom[i], value);
        for (int j = 0; j < blk; j++)
            rom[i + j] = buf[j ^ (value / 4)];
    }
}

void NeoPcm2Swap(std::vector<uint8_t>& v, int value)
{
    static const uint32_t addrs[7][2] = {
        {0x000000,0xa5000},
        {0xffce20,0x01000},
        {0xfe2cf6,0x4e001},
        {0xffac28,0xc2000},
        {0xfeb2c0,0x0a000},
        {0xff14ea,0xa7001},
        {0xffb440,0x02000}};
    static const uint8_t xordata[7][8] = {
        {0xf9,0xe0,0x5d,0xf3,0xea,0x92,0xbe,0xef},
        {0xc4,0x83,0xa8,0x5f,0x21,0x27,0x64,0xaf},
        {0xc3,0xfd,0x81,0xac,0x6d,0xe7,0xbf,0x9e},
        {0xc3,0xfd,0x81,0xac,0x6d,0xe7,0xbf,0x9e},
        {0xcb,0x29,0x7d,0x43,0xd2,0x3a,0xc2,0xb4},
        {0x4b,0xa4,0x63,0x46,0xf0,0x91,0xea,0x62},
        {0x4b,0xa4,0x63,0x46,0xf0,0x91,0xea,0x62}};
    if (value < 0 || value > 6) return;
    const size_t N = 0x1000000;
    if (v.size() < N) v.resize(N, 0);
    std::vector<uint8_t> buf(v.begin(), v.begin() + N);
    for (uint32_t i = 0; i < N; i++)
    {
        // bitswap<24>(i, 23..17, 0, 15..1, 16): swap address bits 0 and 16
        uint32_t j = (i & ~0x10001u) | ((i & 1) << 16) | ((i >> 16) & 1);
        j ^= addrs[value][1];
        const uint32_t d = (i + addrs[value][0]) & 0xffffff;
        v[j & 0xffffff] = buf[d] ^ xordata[value][j & 7];
    }
}

int NeoZ80DriverScore(const std::vector<uint8_t>& m1)
{
    if (m1.size() < 0x100) return 0;
    int s = 0;
    const uint8_t b0 = m1[0], b38 = m1[0x38], b66 = m1[0x66];
    if (b0 == 0xf3 || b0 == 0xc3 || b0 == 0x31 || b0 == 0x18) s += 2;
    if (b38 == 0xc3 || b38 == 0xf3 || b38 == 0xf5 || b38 == 0xfb || b38 == 0xed) s++;
    if (b66 == 0xc3 || b66 == 0xf5 || b66 == 0xed || b66 == 0xf3) s++;
    // bank switching "LD A,n / IN A,(08..0B)" sequences appear in practically every driver
    size_t lim = m1.size() < 0x10000 ? m1.size() : 0x10000;
    int banks = 0;
    for (size_t i = 0; i + 3 < lim; i++)
        if (m1[i] == 0x3e && m1[i + 2] == 0xdb && m1[i + 3] >= 0x08 && m1[i + 3] <= 0x0b) banks++;
    if (banks >= 2) s += 2;
    return s;
}

bool NeoLookupCrypt(uint32_t crc, NeoCryptInfo& info)
{
    struct E { uint32_t crc; int type; int value; const char* name; };
    static const E table[] = {
        { 0x4b749113, 0, 0,  "kof2000" },
        { 0xa7f8119f, 0, 0,  "kof2001" },
        { 0xd163c690, 0, 0,  "jockeygp" },
        { 0x85aaa632, 2, 0,  "kof2002" },
        { 0x456c3e6c, 2, 1,  "matrim" },
        { 0x4a5a6e0e, 2, 2,  "mslug5" },
        { 0xf6819d00, 2, 3,  "svc" },
        { 0x49c9901a, 2, 4,  "samsho5" },
        { 0xf5515629, 2, 5,  "kof2003" },
        { 0x48d9affe, 2, 5,  "kof2003h" },
        { 0xadeebf40, 2, 6,  "samsh5sp" },
        { 0x46ac8228, 1, 8,  "mslug4" },
        { 0x4dbd7b43, 1, 16, "rotd" },
        { 0xc7853ccd, 1, 4,  "pnyaa" },
    };
    for (const E& e : table)
        if (e.crc == crc)
        {
            info.cmc50 = true;
            info.pcm2Type = e.type;
            info.pcm2Value = e.value;
            info.name = e.name;
            return true;
        }
    return false;
}

NeoCryptInfo NeoPrepareM1(std::vector<uint8_t>& m1, uint32_t rawCrc, int mode)
{
    NeoCryptInfo info;
    if (mode == 0) return info;                          // Crypt=none
    if (!NeoLookupCrypt(rawCrc, info) && NeoZ80DriverScore(m1) < 3)
    {
        // unknown set: try CMC50 and keep it if the result looks like a driver
        std::vector<uint8_t> d = m1;
        NeoCmc50M1Decrypt(d);
        if (NeoZ80DriverScore(d) >= 4) { info.cmc50 = true; info.name = "unknown CMC50"; }
    }
    if (mode == 2) info.cmc50 = true;                    // Crypt=cmc50 (force)
    if (info.cmc50) NeoCmc50M1Decrypt(m1);
    return info;
}

void NeoPrepareV(std::vector<uint8_t>& v, const NeoCryptInfo& info)
{
    if (v.empty()) return;
    if (info.pcm2Type == 1) NeoPcm2Decrypt(v, info.pcm2Value);
    else if (info.pcm2Type == 2) NeoPcm2Swap(v, info.pcm2Value);
}
