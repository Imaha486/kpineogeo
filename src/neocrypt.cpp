static inline int bit(uint32_t v, int n) { return (v >> n) & 1; }

// bitswap<16>(v, b15, b14, ..., b0): output bit (15-k) = input bit list[k]
static uint16_t bitswap16(uint16_t v, const int (&b)[16])
{
    uint16_t r = 0;
    for (int k = 0; k < 16; k++)
        r |= bit(v, b[k]) << (15 - k);
    return r;
}

